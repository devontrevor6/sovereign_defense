def generate_mutated_payload(strategy, size):
    if strategy == "EXTREME_PAYLOAD_INFLATION":
        return b"A" * size + b"\x90" * random.randint(1, 128) + b"\xcc"
    elif strategy == "FORMAT_STRING_INJECTION":
        base = b"AUTH_VECTOR " + b"%n%s%p%x" * random.randint(2, 6)
        return base + b"A" * max(0, size - len(base))
    elif strategy == "BOUNDARY_NULL_STUFFING":
        arr = bytearray(random.getrandbits(8) for _ in range(size))
        for i in range(0, len(arr), random.randint(2, 8)):
            arr[i] = 0x00
        return bytes(arr)
    elif strategy == "INTEGER_OVERFLOW_MATRIX":
        return b"\xff\xff\xff\xff" + b"\x00" * 4 + b"B" * (size - 8)
    elif strategy == "HEAP_CORRUPTION_SPRAY":
        return b"\xef\xbe\xad\xde" * (size // 4)
    else:
        return b"\xff\xfe" + b"X" * (size - 2)

def fire_single_probe(strategy, payload_size):
    system_state["metrics"]["total_probes"] += 1
    payload = generate_mutated_payload(strategy, payload_size)
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
            s.settimeout(0.5)
            s.connect((TARGET_HOST, TARGET_PORT))
            s.sendall(payload)
            response = s.recv(1024)
            if b"core dump" in response.lower() or b"segmentation" in response.lower():
                classify_and_record_vulnerability(strategy, payload, "Memory Disclosure / Crash Leak matched")
    except socket.timeout:
        if random.random() < 0.05:
            classify_and_record_vulnerability(strategy, payload, "Socket Timeout / Resource Exhaustion")
    except ConnectionRefusedError:
        if random.random() < 0.1:
            classify_and_record_vulnerability(strategy, payload, "Service Crash / Memory Corruption")
    except ConnectionResetError:
        if random.random() < 0.1:
            classify_and_record_vulnerability(strategy, payload, "Stack/Heap Overflow (Connection Reset)")
    except Exception:
        pass

