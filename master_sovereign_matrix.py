def classify_and_record_vulnerability(strategy, raw_payload, signature):
    payload_size = len(raw_payload)
    
    if b"\xef\xbe\xad\xde" in raw_payload or "Heap" in strategy:
        category = "HEAP_CORRUPTION / MEM_INJECT"
        severity = "CRITICAL"
